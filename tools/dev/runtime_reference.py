"""Generate the Phase 05 runtime API reference from registered core operators."""

from __future__ import annotations

from pathlib import Path

from packages.runtime.src.lengeas_runtime.context import ExecutionBudgets
from packages.runtime.src.lengeas_runtime.effects import CORE_EFFECT_NAMES
from packages.runtime.src.lengeas_runtime.rewards import CORE_REWARD_NAMES

ROOT = Path(__file__).resolve().parents[2]


def render() -> str:
    budgets = ExecutionBudgets()
    return f"""# Runtime API Reference v1

Generated by `tools/dev/runtime_reference.py`; source version is the Phase 05 runtime contract.

## Python package

Import from `packages.runtime.src.lengeas_runtime` in this monorepo. The source package has no
HTTP, persistence, filesystem, environment, network, wall-clock, or unseeded randomness imports.

## Public primitives

- `ExecutionContext`: frozen engine and definition versions/digests, package digests, state version,
  action id, UTC logical time, 128-bit seed, experiment assignments, locale, actor and tenant scope,
  read/write namespaces, and resource budgets.
- `StatePathRegistry`: token-only typed path resolution with read/write role sets, package
  ownership,
  and explicit `error` or `allow_absence` missing-value behavior. Registration freezes before use.
- `evaluate_condition(ast, state, registry, package_id, logical_time)`: pure AST evaluation with
  ordered explanation trees and registered predicate injection.
- `evaluate_formula(ast, variables, allowed_variables=...)`: bounded Decimal evaluator. Division by
  zero, scale loss, numeric overflow, unknown operators, and resource exhaustion raise stable
  errors.
- `plan_action(action, payload, state, context=..., path_registry=...)`: returns a frozen
  `ActionPlan`; input state is never mutated. Operation order is costs, effects, then rewards.
- `HandlerRegistry`: effect/reward handler registration with package ownership and a freeze
  boundary.
- `EventDraft`, `OutboxRecord`, and `InboxKey`: deterministic event drafts plus persistence-facing
  transactional outbox and consumer inbox identities.

## Core handler names

Effects: {", ".join(CORE_EFFECT_NAMES)}.

Rewards: {", ".join(CORE_REWARD_NAMES)}.

## Default budgets

| Budget | Default |
|---|---:|
| Condition nodes | {budgets.condition_nodes} |
| Formula operations | {budgets.formula_operations} |
| Expanded effects | {budgets.effects} |
| Emitted events | {budgets.events} |
| State patch bytes | {budgets.state_patch_bytes} |
| Pure evaluator time (reference CPU) | {budgets.execution_micros} µs |

The caller supplies logical time and seed. The runtime returns plans and explanations. Application
adapters authorize and atomically commit state, receipt, idempotency, and outbox
records. They assign committed event IDs.
"""


def generate() -> None:
    target = ROOT / "docs" / "reference" / "runtime-v1.md"
    target.write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
